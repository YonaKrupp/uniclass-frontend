function renderInline(text, keyPrefix) {
  const parts = [];
  const regex = /(\[[^\]]+\]\([^)]+\)|\*\*[^*]+\*\*|\*[^*]+\*)/g;
  let lastIndex = 0;
  let match;
  let i = 0;
  while ((match = regex.exec(text)) !== null) {
    if (match.index > lastIndex) parts.push(text.slice(lastIndex, match.index));
    const token = match[0];
    if (token.startsWith("[")) {
      const linkMatch = token.match(/^\[([^\]]+)\]\(([^)]+)\)$/);
      const label = linkMatch[1];
      const url = linkMatch[2];
      parts.push(
        url.startsWith("/")
          ? <Link key={`${keyPrefix}-l${i++}`} to={url} className="text-primary underline underline-offset-2">{label}</Link>
          : <a key={`${keyPrefix}-l${i++}`} href={url} target="_blank" rel="noopener noreferrer" className="text-primary underline underline-offset-2">{label}</a>
      );
    } else if (token.startsWith("**")) {
      parts.push(<strong key={`${keyPrefix}-b${i++}`} className="font-semibold text-foreground">{token.slice(2, -2)}</strong>);
    } else {
      parts.push(<em key={`${keyPrefix}-i${i++}`} className="text-muted-foreground">{token.slice(1, -1)}</em>);
    }
    lastIndex = match.index + token.length;
  }
  if (lastIndex < text.length) parts.push(text.slice(lastIndex));
  return parts;
}

function renderDoc(doc) {
  const blocks = [];
  let list = [];
  let key = 0;

  const flushList = () => {
    if (!list.length) return;
    const current = list;
    const listKey = key++;
    blocks.push(
      <ul key={`ul-${listKey}`} className="list-disc pr-6 space-y-2">
        {current.map((item, idx) => (
          <li key={idx}>{renderInline(item, `ul-${listKey}-${idx}`)}</li>
        ))}
      </ul>
    );
    list = [];
  };

  doc.split("\n").forEach((raw) => {
    const line = raw.trim();
    if (!line) {
      flushList();
      return;
    }
    if (line.startsWith("- ")) {
      list.push(line.slice(2));
      return;
    }
    flushList();
    if (line.startsWith("## ")) {
      const k = key++;
      blocks.push(
        <h2 key={`h2-${k}`} className="text-xl sm:text-2xl font-heading font-bold text-foreground pt-4">
          {renderInline(line.slice(3), `h2-${k}`)}
        </h2>
      );
    } else if (line.startsWith("# ")) {
      const k = key++;
      blocks.push(
        <h1 key={`h1-${k}`} className="text-3xl sm:text-4xl font-heading font-bold text-foreground">
          {renderInline(line.slice(2), `h1-${k}`)}
        </h1>
      );
    } else if (line === "---") {
      blocks.push(<hr key={`hr-${key++}`} className="border-border" />);
    } else {
      const k = key++;
      blocks.push(<p key={`p-${k}`}>{renderInline(line, `p-${k}`)}</p>);
    }
  });

  flushList();
  return blocks;
}

